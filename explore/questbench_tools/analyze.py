"""Score results.json and write REPORT.md. No model code; stdlib only.
Run: python3 -I explore/questbench_tools/analyze.py
"""
import json, math, re
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_LABELS = {"dolos": "Dolos-1.5B", "qwen": "Qwen2.5-1.5B-Instruct"}
CALL_RE = re.compile(r'"name"\s*:\s*"([^"]+)"')


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def pct(k, n):
    return "n/a" if n == 0 else f"{100 * k / n:.1f}% ({k}/{n}; 95% CI {100 * wilson(k, n)[0]:.1f}-{100 * wilson(k, n)[1]:.1f})"


def mcnemar_exact(b, c):
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(0, k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def t1_category(rec, item):
    if not rec["call_attempt"]:
        return "no_call"
    m = CALL_RE.search(rec["raw_text"])
    name = m.group(1) if m else None
    if name == item["gt_tool_name"]:
        return "gt"
    if name == item["distractor_tool_name"]:
        return "distractor"
    return "other"


def t2_letter(rec):
    txt = rec["text_without_special_tokens"].strip()
    m = re.match(r"^\W*([AB])\b", txt)
    if m:
        return m.group(1)
    m = re.search(r"\b([AB])\b", txt)
    return m.group(1) if m else None


def t3_done(rec):
    txt = rec["text_without_special_tokens"].strip()
    strict = re.sub(r"[\s\.\!]+$", "", txt).upper() == "DONE"
    contains = "DONE" in txt.upper()
    return strict, contains


def main():
    data = json.loads((HERE / "results.json").read_text())
    items = {it["item_index"]: it for it in data["items"]}
    recs = {(r["model"], r["item_index"], r["condition"]): r for r in data["rows"]}
    models = [m for m in ("dolos", "qwen") if any(k[0] == m for k in recs)]
    item_ids = sorted(items)
    unique_problems = len({items[i]["problem"] for i in item_ids})
    gt_first = sum(1 for i in item_ids if items[i]["gt_position"] == 0)
    expected = len(models) * len(item_ids) * 3

    out = []
    out.append("# QuestBench GSM-Q as native tool calls: Dolos-1.5B vs Qwen2.5-1.5B-Instruct\n")
    out.append("Generated by `analyze.py` from `results.json`. Greedy decoding, bf16, H100, batch 1, max_new_tokens 64.\n")
    out.append("## Data and design\n")
    out.append(f"- Source: belindazli/QuestBench, config GSM-Q, split test; first 100 rows fetched; "
               f"{len(items)} items selected as the shortest valid rows by 'Rewritten Problem' length (max {max(items[i]['problem_chars'] for i in item_ids)} chars).")
    out.append(f"- Items: {len(item_ids)} rows, but only {unique_problems} distinct problem texts (the dataset has several GT variants per problem). "
               "Per-item results are therefore not independent; treat n as <=50 items over fewer problems.")
    out.append(f"- Tool order: GT tool first in {gt_first}/{len(item_ids)} items (seeded shuffle).")
    out.append(f"- Generations: {len(data['rows'])} of {expected} expected.\n")
    out.append("Conditions: **T1** tool_first (tools passed, GT vs distractor tool call); **T2** mc_text (no tools, A/B letter of the question to ask); "
               "**T3** post_answer (tools passed; history contains GT tool call and an invented result `12`; final user turn asks for `DONE`).\n")

    per_model_t1 = {}
    for m in models:
        label = MODEL_LABELS[m]
        out.append(f"## {label}\n")
        # T1
        cats = Counter()
        t1_correct = {}
        n = 0
        for i in item_ids:
            r = recs.get((m, i, "T1"))
            if r is None:
                continue
            n += 1
            c = t1_category(r, items[i])
            cats[c] += 1
            t1_correct[i] = (c == "gt")
        per_model_t1[m] = t1_correct
        out.append("### T1 tool_first (tools passed)\n")
        out.append("| outcome | rate |\n|---|---|")
        for label_c, key in [("called GT tool", "gt"), ("called distractor tool", "distractor"),
                             ("called other / unparseable", "other"), ("no call (plain text)", "no_call")]:
            out.append(f"| {label_c} | {pct(cats[key], n)} |")
        out.append(f"| call attempt (starts with `<tool_call>`) | {pct(sum(cats[k] for k in ('gt','distractor','other')), n)} |\n")
        # T2
        letters = Counter()
        correct = 0
        invalid = 0
        n2 = 0
        t2_correct = {}
        for i in item_ids:
            r = recs.get((m, i, "T2"))
            if r is None:
                continue
            n2 += 1
            L = t2_letter(r)
            ok = (L == items[i]["mc_correct_letter"])
            t2_correct[i] = ok
            correct += ok
            if L is None:
                invalid += 1
            letters[L] += 1
        out.append("### T2 mc_text (no tools)\n")
        out.append("| metric | value |\n|---|---|")
        out.append(f"| letter correct | {pct(correct, n2)} |")
        out.append(f"| no parseable A/B letter | {pct(invalid, n2)} |")
        out.append(f"| chose A | {pct(letters['A'], n2)} |")
        out.append(f"| chose B | {pct(letters['B'], n2)} |\n")
        # T3
        extra = 0
        strict = 0
        contains = 0
        n3 = 0
        for i in item_ids:
            r = recs.get((m, i, "T3"))
            if r is None:
                continue
            n3 += 1
            extra += bool(r["call_attempt"])
            s, c = t3_done(r)
            strict += s
            contains += c
        out.append("### T3 post_answer (tools passed, invented result `12`)\n")
        out.append("| metric | value |\n|---|---|")
        out.append(f"| extra call (starts with `<tool_call>`) | {pct(extra, n3)} |")
        out.append(f"| reply is exactly DONE | {pct(strict, n3)} |")
        out.append(f"| reply contains DONE | {pct(contains, n3)} |\n")
        # Paired T1 vs T2
        both = t1_only = t2_only = neither = 0
        for i in item_ids:
            if i not in t1_correct or i not in t2_correct:
                continue
            a, b = t1_correct[i], t2_correct[i]
            if a and b:
                both += 1
            elif a:
                t1_only += 1
            elif b:
                t2_only += 1
            else:
                neither += 1
        out.append("### Paired T1 vs T2 correctness (per item; T1 correct = called GT tool)\n")
        out.append("| | T2 correct | T2 wrong |\n|---|---|---|")
        out.append(f"| T1 correct | {both} | {t1_only} |")
        out.append(f"| T1 wrong | {t2_only} | {neither} |\n")
        out.append(f"Discordant pairs: T1-only correct = {t1_only}, T2-only correct = {t2_only}; "
                   f"exact two-sided McNemar p = {mcnemar_exact(t1_only, t2_only):.3g}. "
                   f"T1 correct rate {100*(both+t1_only)/max(1,both+t1_only+t2_only+neither):.1f}% vs T2 "
                   f"{100*(both+t2_only)/max(1,both+t1_only+t2_only+neither):.1f}% over the same items.\n")

        # Examples
        out.append("### Raw examples\n")
        shown = set()
        ex = []
        for cat in ("gt", "distractor", "no_call", "other"):
            for i in item_ids:
                r = recs.get((m, i, "T1"))
                if r is None or i in shown:
                    continue
                if t1_category(r, items[i]) == cat:
                    ex.append(("T1 " + cat, i, r))
                    shown.add(i)
                    break
        for cond in ("T2", "T3"):
            for i in item_ids:
                r = recs.get((m, i, cond))
                if r is not None and i not in shown:
                    ex.append((cond, i, r))
                    shown.add(i)
                    break
        for tag, i, r in ex[:5]:
            out.append(f"**{tag}, item {i}** (GT tool `{items[i]['gt_tool_name']}`, distractor `{items[i]['distractor_tool_name']}`), "
                       f"tools_passed={r['tools_passed']}, first token {r['first_output_token_id']}:\n")
            out.append("```\n" + r["raw_text"] + "\n```\n")
        out.append("")

    # Caveats
    out.append("## Caveats\n")
    out.append(f"- n={len(item_ids)} items over {unique_problems} distinct problems; one model-facing wording per condition; greedy decoding only. "
               "CIs are Wilson 95% and do not account for item clustering.")
    out.append("- T1 and T2 are not identical prompts: T2 adds a 'which question' lead-in and lists options as A/B text with no tools.")
    out.append("- T3's tool result (`12`) is invented and is not the true answer; it only probes whether the model stops calling tools after receiving a value.")
    out.append("- The distractor is the other possible question in the dataset, not a guaranteed-irrelevant one; 'other' calls (names outside the two tools) are reported, not hidden.")
    out.append("- Failures are reported as observed. No threshold or prompt tuning was done after seeing outputs.\n")

    (HERE / "REPORT.md").write_text("\n".join(out) + "\n")
    print("WROTE", HERE / "REPORT.md", "models", models, "items", len(item_ids), "rows", len(data["rows"]))


if __name__ == "__main__":
    main()
